y = np.arange(len(top_subcats))
height = 0.35
ax4.barh(y + height/2, top_subcats['south_share_pct'], height,
         color='#D7191C', alpha=0.85, label='South share %')
ax4.barh(y - height/2, top_subcats['west_share_pct'], height,
         color='#2C7BB6', alpha=0.85, label='West share %')
ax4.set_yticks(y)
ax4.set_yticklabels(top_subcats['Sub-Category'])
ax4.set_title('South vs West Volume Share\n(Top 10 Sub-Categories by Revenue)', fontweight='bold')
ax4.set_xlabel('% Share of Transactions')
ax4.axvline(x=25, color='gray', linestyle='--', linewidth=1, label='25% equal share baseline')
ax4.legend(loc='lower right')

plt.tight_layout()
plt.savefig('regional_sales_analysis.png', dpi=150, bbox_inches='tight')
plt.show()
print("Chart saved.")

