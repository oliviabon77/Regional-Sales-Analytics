# Load raw data
# In Google Colab: upload train.csv using the folder icon on the left sidebar
df = pd.read_csv('/train.csv', encoding='latin1')

print(f"Raw dataset: {df.shape[0]:,} rows, {df.shape[1]} columns")
print(f"Columns: {df.columns.tolist()}")

# ============================================================
# CELL 3: Data validation and cleaning
# ============================================================

# Fix date parsing — dates are in DD/MM/YYYY format
df['Order Date'] = pd.to_datetime(df['Order Date'], dayfirst=True)
df['Ship Date']  = pd.to_datetime(df['Ship Date'],  dayfirst=True)

# Check for nulls
print("\nNull counts per column:")
print(df.isnull().sum()[df.isnull().sum() > 0])

# Postal code has 11 nulls — acceptable, not used in regional analysis
# All other key fields are complete

# Validate regions
print(f"\nRegions present: {sorted(df['Region'].unique())}")
print(f"Categories present: {sorted(df['Category'].unique())}")
print(f"Date range: {df['Order Date'].min().date()} to {df['Order Date'].max().date()}")
print(f"Total rows after cleaning: {len(df):,}")

# Register with DuckDB for SQL analysis
con = duckdb.connect()
con.register('sales', df)

print("\nData loaded and validated.")

# ============================================================
# CELL 4: Regional revenue summary
# ============================================================

# Step 1: Understand the overall revenue distribution by region
# This is the starting point — we see a gap and then investigate why

region_summary = con.execute("""
    SELECT
        Region,
        ROUND(SUM(Sales), 2)                   AS total_revenue,
        COUNT(DISTINCT "Order ID")             AS total_orders,
        COUNT(DISTINCT "Customer ID")          AS unique_customers,
        ROUND(AVG(Sales), 2)                   AS avg_order_value,
        ROUND(SUM(Sales) / COUNT(DISTINCT "Customer ID"), 2) AS revenue_per_customer
    FROM sales
    GROUP BY Region
    ORDER BY total_revenue DESC
""").df()

print("Regional revenue summary:")
print(region_summary.to_string(index=False))

# Calculate the gap between top and bottom region
top_region    = region_summary.iloc[0]
bottom_region = region_summary.iloc[-1]
gap_pct = round((top_region['total_revenue'] - bottom_region['total_revenue'])
                / top_region['total_revenue'] * 100, 1)

print(f"\nRevenue gap between {top_region['Region']} and {bottom_region['Region']}: {gap_pct}%")
print("This gap is the starting point for our root cause investigation.")

# ============================================================
# CELL 5: Drill into revenue by category and region
# ============================================================

# Step 2: Break the gap down by product category to isolate where it comes from

category_region = con.execute("""
    SELECT
        Category,
        Region,
        ROUND(SUM(Sales), 2)          AS total_revenue,
        COUNT(DISTINCT "Order ID")    AS orders,
        ROUND(AVG(Sales), 2)          AS avg_order_value
    FROM sales
    GROUP BY Category, Region
    ORDER BY Category, total_revenue DESC
""").df()

print("Revenue by category and region:")
print(category_region.to_string(index=False))

# Pivot for easier comparison
category_pivot = category_region.pivot(
    index='Category', columns='Region', values='total_revenue'
).round(2)
print("\nPivoted category revenue by region:")
print(category_pivot.to_string())

# ============================================================
# CELL 6: Pricing inconsistency analysis by sub-category
# ============================================================

# Step 3: Look at average sale value by sub-category across regions
# Pricing inconsistencies show up as large differences in avg_order_value
# for the same product across different regions

pricing_analysis = con.execute("""
    SELECT
        "Sub-Category",
        ROUND(AVG(CASE WHEN Region = 'West'    THEN Sales END), 2) AS west_avg,
        ROUND(AVG(CASE WHEN Region = 'East'    THEN Sales END), 2) AS east_avg,
        ROUND(AVG(CASE WHEN Region = 'Central' THEN Sales END), 2) AS central_avg,
        ROUND(AVG(CASE WHEN Region = 'South'   THEN Sales END), 2) AS south_avg,
        ROUND(AVG(Sales), 2)                                        AS overall_avg,
        COUNT(*)                                                    AS total_transactions
    FROM sales
    GROUP BY "Sub-Category"
    ORDER BY overall_avg DESC
""").df()

# Calculate max pricing spread across regions for each sub-category
pricing_analysis['price_spread'] = (
    pricing_analysis[['west_avg', 'east_avg', 'central_avg', 'south_avg']]
    .apply(lambda row: round(
        (row.max() - row.min()) / row.mean() * 100, 1
    ), axis=1)
)

print("Pricing analysis by sub-category (avg sale value per region):")
print(pricing_analysis.sort_values('price_spread', ascending=False).to_string(index=False))

# Identify sub-categories with the largest pricing spread
print("\nTop 5 sub-categories with largest regional pricing inconsistencies:")
top_inconsistent = pricing_analysis.nlargest(5, 'price_spread')[
    ['Sub-Category', 'west_avg', 'east_avg', 'central_avg', 'south_avg', 'price_spread']
]
print(top_inconsistent.to_string(index=False))

# ============================================================
# CELL 7: Volume distribution analysis
# ============================================================

# Step 4: Check whether the gap is also driven by uneven volume distribution
# i.e. high-value products concentrated in certain regions

volume_distribution = con.execute("""
    SELECT
        "Sub-Category",
        SUM(CASE WHEN Region = 'West'    THEN 1 ELSE 0 END) AS west_count,
        SUM(CASE WHEN Region = 'East'    THEN 1 ELSE 0 END) AS east_count,
        SUM(CASE WHEN Region = 'Central' THEN 1 ELSE 0 END) AS central_count,
        SUM(CASE WHEN Region = 'South'   THEN 1 ELSE 0 END) AS south_count,
        COUNT(*)                                             AS total,
        ROUND(SUM(Sales), 2)                                AS total_revenue
    FROM sales
    GROUP BY "Sub-Category"
    ORDER BY total_revenue DESC
""").df()

# Calculate South's share of each sub-category
volume_distribution['south_share_pct'] = round(
    volume_distribution['south_count'] / volume_distribution['total'] * 100, 1
)
volume_distribution['west_share_pct'] = round(
    volume_distribution['west_count'] / volume_distribution['total'] * 100, 1
)

print("Volume distribution by sub-category:")
print(volume_distribution[['Sub-Category', 'west_count', 'east_count',
                            'central_count', 'south_count', 'total',
                            'south_share_pct']].to_string(index=False))

# ============================================================
# CELL 8: Root cause — focus on Machines sub-category
# ============================================================

# Machines shows the largest pricing spread across regions:
# South avg = $2,993 vs West avg = $1,088 — a 175% difference
# This is the primary pricing inconsistency driving the revenue gap

machines_analysis = con.execute("""
    SELECT
        Region,
        COUNT(*)                       AS transactions,
        ROUND(SUM(Sales), 2)          AS total_revenue,
        ROUND(AVG(Sales), 2)          AS avg_sale_value,
        ROUND(MIN(Sales), 2)          AS min_sale,
        ROUND(MAX(Sales), 2)          AS max_sale
    FROM sales
    WHERE "Sub-Category" = 'Machines'
    GROUP BY Region
    ORDER BY avg_sale_value DESC
""").df()

print("Machines sub-category deep dive:")
print(machines_analysis.to_string(index=False))

# Copiers also shows large spread
copiers_analysis = con.execute("""
    SELECT
        Region,
        COUNT(*)                       AS transactions,
        ROUND(SUM(Sales), 2)          AS total_revenue,
        ROUND(AVG(Sales), 2)          AS avg_sale_value
    FROM sales
    WHERE "Sub-Category" = 'Copiers'
    GROUP BY Region
    ORDER BY avg_sale_value DESC
""").df()

print("\nCopiers sub-category deep dive:")
print(copiers_analysis.to_string(index=False))

# ============================================================
# CELL 9: Revenue gap attribution
# ============================================================

# Quantify how much of the West-South gap is explained by
# Machines and Copiers pricing differences

gap_attribution = con.execute("""
    WITH region_subcat AS (
        SELECT Region, "Sub-Category",
               SUM(Sales) AS revenue,
               COUNT(*) AS transactions,
               AVG(Sales) AS avg_price
        FROM sales
        GROUP BY Region, "Sub-Category"
    ),
    west_baseline AS (
        SELECT "Sub-Category", avg_price AS west_avg_price
        FROM region_subcat WHERE Region = 'West'
    ),
    south_actual AS (
        SELECT r."Sub-Category",
               r.revenue AS south_revenue,
               r.transactions AS south_transactions,
               r.avg_price AS south_avg_price,
               w.west_avg_price,
               ROUND((r.avg_price - w.west_avg_price) * r.transactions, 2) AS pricing_effect
        FROM region_subcat r
        JOIN west_baseline w ON r."Sub-Category" = w."Sub-Category"
        WHERE r.Region = 'South'
    )
    SELECT "Sub-Category",
           south_revenue,
           south_transactions,
           ROUND(south_avg_price, 2) AS south_avg,
           ROUND(west_avg_price, 2)  AS west_avg,
           pricing_effect
    FROM south_actual
    ORDER BY ABS(pricing_effect) DESC
""").df()

print("Revenue gap attribution — pricing effect of each sub-category:")
print("(Positive = South charges more than West; Negative = South charges less)")
print(gap_attribution.to_string(index=False))

total_gap = region_summary.iloc[0]['total_revenue'] - region_summary.iloc[-1]['total_revenue']
print(f"\nTotal West-South revenue gap: ${total_gap:,.2f}")
print(f"Gap as % of West revenue: {gap_pct}%")

